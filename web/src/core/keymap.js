export function keyToBios(e) {
  const k = T[e.code]; if (!k) return null;
  let [scan, ascii] = k;
  if (e.shiftKey && ascii >= 0x61 && ascii <= 0x7a) ascii -= 0x20;
  if (e.ctrlKey && ascii >= 0x61 && ascii <= 0x7a) ascii -= 0x60;
  return [scan, ascii];
}
